def resolve_lang(candidate: str | None, accept_language: str | None = None) -> str:
    """Parenka kalbą pagal pateiktą kodą arba naršyklės Accept-Language antraštę."""
    if candidate and candidate in TRANSLATIONS:
        return candidate
    if accept_language:
        for part in accept_language.split(","):
            code = part.split(";")[0].strip().lower()[:2]
            if code in TRANSLATIONS:
                return code
    return DEFAULT


def get(lang: str) -> dict[str, str]:
    """Grąžina vertimų žodyną nurodytai kalbai (su atsarga į numatytąją)."""
    return TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT])
